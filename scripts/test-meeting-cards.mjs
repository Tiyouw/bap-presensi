import assert from "node:assert/strict";
import { nextMeetingCard, additionError } from "../src/lib/meetingCards.js";
import { validScheduleDraft } from "../src/lib/draftFile.js";
const first=nextMeetingCard([],[],{},"F6");
assert.match(first.tanggal,/^\d{4}-\d{2}-\d{2}$/);
first.tanggal="2026-12-28";
const second=nextMeetingCard([],[first],{},"F6");assert.equal(second.tanggal,"2027-01-04");assert.equal(second.nomor,2);
second.tanggal="2028-02-25";assert.equal(nextMeetingCard([],[first,second],{},"F6").tanggal,"2028-03-03");
assert.equal(nextMeetingCard([{id:"p1",nomor:1,tanggal:"2026-01-01"}],[],{p1:{tanggal:"2026-04-01"}},"F6").tanggal,"2026-04-08");
assert.throws(()=>nextMeetingCard([],[{...first,tanggal:""}],{},"F6"),/Periksa tanggal/);
assert.throws(()=>nextMeetingCard([],[{...first,tanggal:"9999-12-30"}],{},"F6"),/batas kalender/);
assert.equal(additionError([], [first,second]),null);
assert.equal(additionError([],[first,{...second,nomor:1}]).field,"nomor");
assert.equal(additionError([],[{...first,tempat:" "}]).field,"tempat");
const draft={version:1,base:1,meetings:{},selected:[],patches:{},reason:"",includeHistorical:false,operationKey:crypto.randomUUID(),additions:[first],addRequest:{expectedClassRevision:1,operationKey:crypto.randomUUID(),items:[{nomor:first.nomor,tanggal:first.tanggal,tempat:first.tempat,tipe:first.tipe}]}};
assert(validScheduleDraft(JSON.parse(JSON.stringify(draft))));
assert(!validScheduleDraft({...draft,addRequest:{...draft.addRequest,operationKey:"bad"}}));
assert(!validScheduleDraft({...draft,additions:[first,first]}));
assert(validScheduleDraft({...draft,additions:undefined,addRequest:undefined}));
console.log("Meeting cards: weekly defaults, year/leap boundaries, validation, legacy drafts and immutable retry-envelope validation passed.");
